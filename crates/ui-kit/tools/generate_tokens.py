#!/usr/bin/env python3
"""Generate the ui-kit token modules from the Vynatix design-system tokens.

Reads `../../../.afk/design-system/tokens.json` (relative to the crate
directory; the script also resolves it from its own location, so any
working directory works) and writes generated Rust under `src/tokens/`:

  colors.rs        the 54 per-theme colour roles as `ThemeColors`, one
                   const per theme, a name-keyed role lookup and the
                   convenience alias methods; `{palette-ref}` values are
                   resolved (chained refs included) and `rgba()` values
                   keep their alpha (quantised to 255ths)
  shadows.rs       the per-theme box-shadow strings parsed into typed
                   `ShadowLayer` slices, plus the glass specular edges
  spacing.rs radii.rs type_scale.rs leading.rs tracking.rs
  breakpoints.rs containers.rs icons.rs
                   the scalar scales, each with an `ALL` (name, value)
                   table in tokens.json order
  motion.rs        the motion constants; tokens.json carries no motion
                   section, so these are pinned from the design system
                   README ("Animation")
  snapshot.txt     every resolved role value per theme: the fixture the
                   crate's tests validate the generated code against

Generated files are committed; builds never run this script. After the
token source changes, regenerate from the crate directory, format, and
commit the result:

  python3 tools/generate_tokens.py && cargo fmt

`--stub` writes the same structure with placeholder values (transparent
colours, zeroed scales and shadow geometry) while `snapshot.txt` keeps
the real resolved values: it exists so the crate's token tests can be
shown failing before real generation (red) and passing after (green).
"""

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
TOKENS_JSON = ROOT / ".afk" / "design-system" / "tokens.json"
OUT_DIR = Path(__file__).resolve().parents[1] / "src" / "tokens"

HEADER = (
    "Generated by tools/generate_tokens.py from "
    ".afk/design-system/tokens.json. DO NOT EDIT: rerun the generator "
    "(see src/tokens/mod.rs)."
)

RGBA_RE = re.compile(
    r"rgba\(\s*(\d+)\s*,\s*(\d+)\s*,\s*(\d+)\s*,\s*([\d.]+)\s*\)"
)
SCALAR_RE = re.compile(r"^(-?\d+(?:\.\d+)?)(?:px|em|%)?$")
LAYER_NUM_RE = re.compile(r"^(-?\d+(?:\.\d+)?)(?:px)?$")

EXPECTED_ROLE_COUNT = 54


def die(message: str) -> None:
    raise SystemExit(f"generate_tokens.py: {message}")


# ---- colour parsing and resolution -------------------------------------


def parse_color(value: str) -> tuple[int, int, int, int]:
    """One colour literal to straight (r, g, b, a) with a in 0..=255."""
    value = value.strip()
    if value.startswith("#"):
        hexpart = value[1:]
        if len(hexpart) != 6:
            die(f"unsupported hex colour: {value!r}")
        return (
            int(hexpart[0:2], 16),
            int(hexpart[2:4], 16),
            int(hexpart[4:6], 16),
            255,
        )
    match = RGBA_RE.fullmatch(value)
    if not match:
        die(f"unparsable colour: {value!r}")
    alpha = int(float(match.group(4)) * 255 + 0.5)
    return (int(match.group(1)), int(match.group(2)), int(match.group(3)), alpha)


def split_token_maps(data: dict) -> tuple[dict, dict, dict]:
    """color.tokens split into constants, per-theme roles, and aliases."""
    constants: dict[str, dict] = {}
    roles: dict[str, dict] = {}
    aliases: dict[str, dict] = {}
    for token in data["color"]["tokens"]:
        name, value = token["name"], token["value"]
        if isinstance(value, dict):
            roles[name] = token
        elif isinstance(value, str) and value.startswith("{") and value.endswith("}"):
            token = dict(token)
            token["ref"] = value[1:-1]
            aliases[name] = token
        else:
            constants[name] = token
    if len(roles) != EXPECTED_ROLE_COUNT:
        die(
            f"expected {EXPECTED_ROLE_COUNT} per-theme roles, found "
            f"{len(roles)}; the generator and the crate tests agree on 54"
        )
    return constants, roles, aliases


def resolve(name: str, theme: str, constants: dict, roles: dict, aliases: dict):
    """Resolve one token name for one theme, following refs to any depth."""
    if name in constants:
        return parse_color(constants[name]["value"])
    if name in roles:
        value = roles[name]["value"].get(theme)
        if value is None:
            die(f"role {name!r} has no value for theme {theme!r}")
        if value.startswith("{") and value.endswith("}"):
            return resolve(value[1:-1], theme, constants, roles, aliases)
        return parse_color(value)
    if name in aliases:
        return resolve(aliases[name]["ref"], theme, constants, roles, aliases)
    die(f"unresolved token ref: {name!r}")


def rust_color(rgba: tuple[int, int, int, int], stub: bool) -> str:
    if stub:
        return "Color32::TRANSPARENT"
    r, g, b, a = rgba
    if a == 255:
        return f"Color32::from_rgb({r}, {g}, {b})"
    return f"Color32::from_rgba_unmultiplied_const({r}, {g}, {b}, {a})"


def const_suffix(theme_id: str) -> str:
    return theme_id.replace("-", "_").upper()


def field_name(role: str) -> str:
    return role.removeprefix("md-sys-color-").replace("-", "_")


def rust_f32(value: float, stub: bool) -> str:
    return "0.0" if stub else repr(float(value))


# ---- module emitters ----------------------------------------------------


def scalar_module(data: dict, section: str, module: str, what: str, stub: bool) -> str:
    tokens = data[section]["tokens"]
    lines = [f"//! {HEADER}", f"//! {what}"]
    note = data[section].get("note")
    if note:
        lines.append(f"//! {note}")
    lines.append("")
    for token in tokens:
        value = parse_scalar(token["value"])
        lines.append(f"/// `{token['name']}`: {token['usage']}")
        lines.append(f"pub const {const_name(token['name'])}: f32 = {rust_f32(value, stub)};")
        lines.append("")
    lines.append(f"/// Every {module} token (name, value), in `tokens.json` order.")
    lines.append("pub const ALL: &[(&str, f32)] = &[")
    for token in tokens:
        value = parse_scalar(token["value"])
        lines.append(f"    (\"{token['name']}\", {rust_f32(value, stub)}),")
    lines.append("];")
    lines.append("")
    return "\n".join(lines)


def const_name(token_name: str) -> str:
    return token_name.replace("-", "_").upper()


def parse_scalar(value: str) -> float:
    match = SCALAR_RE.match(value)
    if not match:
        die(f"unparsable scalar token: {value!r}")
    return float(match.group(1))


def gen_colors(data: dict, stub: bool) -> str:
    themes = [t["id"] for t in data["color"]["themes"]]
    names = {t["id"]: t["name"] for t in data["color"]["themes"]}
    constants, roles, aliases = split_token_maps(data)
    role_names = list(roles)

    lines = [f"//! {HEADER}", "//! The 54 per-theme colour roles, resolved.", "", "use egui::Color32;", ""]
    lines += [
        "/// The 54 resolved colour roles of one theme: every `color.tokens`",
        "/// entry whose value is a per-theme mapping, in `tokens.json` order.",
        "/// Screens read roles, never palette constants or raw hex; roles",
        "/// change with the theme, palettes do not.",
        "#[derive(Clone, Copy, Debug, PartialEq)]",
        "pub struct ThemeColors {",
    ]
    for role in role_names:
        usage = roles[role]["usage"].replace("\n", " ")
        lines.append(f"    /// `{role}`: {usage}")
        lines.append(f"    pub {field_name(role)}: Color32,")
    lines.append("}")
    lines.append("")

    for theme in themes:
        lines.append("impl ThemeColors {")
        default = ", the default theme" if theme == "light" else ""
        lines.append(f"    /// {names[theme]} (`{theme}`{default}).")
        lines.append(f"    pub const {const_suffix(theme)}: ThemeColors = ThemeColors {{")
        for role in role_names:
            rgba = resolve(role, theme, constants, roles, aliases)
            lines.append(f"        {field_name(role)}: {rust_color(rgba, stub)},")
        lines.append("    };")
        lines.append("}")
        lines.append("")

    lines.append("impl ThemeColors {")
    lines.append("    /// All 54 role names, in `tokens.json` order.")
    lines.append("    pub const ROLES: &'static [&'static str] = &[")
    for role in role_names:
        lines.append(f"        \"{role}\",")
    lines.append("    ];")
    lines.append("")
    lines.append("    /// Look a role up by its `tokens.json` (kebab-case) name.")
    lines.append("    pub fn role(&self, name: &str) -> Option<Color32> {")
    lines.append("        match name {")
    for role in role_names:
        lines.append(f"            \"{role}\" => Some(self.{field_name(role)}),")
    lines.append("            _ => None,")
    lines.append("        }")
    lines.append("    }")
    lines.append("}")
    lines.append("")

    lines.append("impl ThemeColors {")
    for alias in aliases:
        token = aliases[alias]
        target = token["ref"]
        if target not in roles:
            die(f"alias {alias!r} points at {target!r}, which is not a role")
        lines.append(f"    /// `{alias}`: {token['usage']}")
        lines.append(f"    pub const fn {field_name(alias)}(&self) -> Color32 {{")
        lines.append(f"        self.{field_name(target)}")
        lines.append("    }")
        lines.append("")
    lines.append("}")
    lines.append("")
    return "\n".join(lines)


# ---- shadows ------------------------------------------------------------


def split_layers(shadow: str) -> list[str]:
    layers, depth, current = [], 0, ""
    for ch in shadow:
        if ch == "(":
            depth += 1
        elif ch == ")":
            depth -= 1
        if ch == "," and depth == 0:
            layers.append(current.strip())
            current = ""
        else:
            current += ch
    if current.strip():
        layers.append(current.strip())
    return layers


def parse_layer(layer: str) -> dict:
    inset = layer.startswith("inset")
    if inset:
        layer = layer[len("inset") :].strip()
    match = RGBA_RE.search(layer)
    if not match:
        die(f"shadow layer without an rgba colour: {layer!r}")
    color = parse_color(match.group(0))
    numbers = []
    for part in layer[: match.start()].split():
        number = LAYER_NUM_RE.match(part)
        if number:
            numbers.append(float(number.group(1)))
    while len(numbers) < 4:
        numbers.append(0.0)
    x, y, blur, spread = numbers[:4]
    return {"inset": inset, "x": x, "y": y, "blur": blur, "spread": spread, "color": color}


def rust_layer(layer: dict, stub: bool) -> str:
    return (
        "ShadowLayer {"
        f"inset: {str(layer['inset']).lower()}, "
        f"x: {rust_f32(layer['x'], stub)}, "
        f"y: {rust_f32(layer['y'], stub)}, "
        f"blur: {rust_f32(layer['blur'], stub)}, "
        f"spread: {rust_f32(layer['spread'], stub)}, "
        f"color: {rust_color(layer['color'], stub)}"
        "}"
    )


def gen_shadows(data: dict, stub: bool) -> str:
    tokens = {t["name"]: t for t in data["shadow"]["tokens"]}
    themes = [t["id"] for t in data["color"]["themes"]]
    level_usage = {
        level: tokens[f"shadow-{level}"]["usage"] for level in ("l1", "l2", "l3", "l4", "l5")
    }

    lines = [
        f"//! {HEADER}",
        "//! The per-theme box-shadow strings, parsed into typed layers.",
        "",
        "use egui::Color32;",
        "",
        "/// One parsed CSS box-shadow layer, geometry in px. Layers stay",
        "/// raw because egui's own shadow cannot express more than one",
        "/// layer, a negative spread or an inset edge; `theme` picks a",
        "/// single-layer approximation when it skins egui shadows.",
        "#[derive(Clone, Copy, Debug, PartialEq)]",
        "pub struct ShadowLayer {",
        "    /// True for `inset` shadows (the glass specular edge).",
        "    pub inset: bool,",
        "    /// Horizontal offset.",
        "    pub x: f32,",
        "    /// Vertical offset.",
        "    pub y: f32,",
        "    /// Penumbral width.",
        "    pub blur: f32,",
        "    /// Outward growth, or inward when negative.",
        "    pub spread: f32,",
        "    /// The tint, alpha included.",
        "    pub color: Color32,",
        "}",
        "",
        "/// The five elevation levels of one theme. Pair each level with",
        "/// its surface-container colour, per the design system; level 0",
        "/// is flat (`none`) and carries no layers.",
        "#[derive(Clone, Copy, Debug)]",
        "pub struct ThemeShadows {",
    ]
    for level in ("l1", "l2", "l3", "l4", "l5"):
        lines.append(f"    /// {level_usage[level]}")
        lines.append(f"    pub {level}: &'static [ShadowLayer],")
    lines.append("}")
    lines.append("")

    for theme in themes:
        names = {t["id"]: t["name"] for t in data["color"]["themes"]}
        lines.append(f"/// {names[theme]} (`{theme}`).")
        lines.append(f"pub const {const_suffix(theme)}: ThemeShadows = ThemeShadows {{")
        for level in ("l1", "l2", "l3", "l4", "l5"):
            layers = split_layers(tokens[f"shadow-{level}"]["value"][theme])
            lines.append(f"    {level}: &[")
            for layer in layers:
                parsed = parse_layer(layer)
                lines.append(f"        {rust_layer(parsed, stub)},")
            lines.append("    ],")
        lines.append("};")
        lines.append("")

    for name in ("glass-specular-light", "glass-specular-dark"):
        token = tokens[name]
        lines.append(f"/// `{name}`: {token['usage']}")
        lines.append(f"pub const {const_name(name)}: &[ShadowLayer] = &[")
        for layer in split_layers(token["value"]):
            parsed = parse_layer(layer)
            lines.append(f"    {rust_layer(parsed, stub)},")
        lines.append("];")
        lines.append("")
    return "\n".join(lines)


# ---- motion (README-pinned; tokens.json has no motion section) ----------


def gen_motion() -> str:
    lines = [
        f"//! {HEADER}",
        "//! Motion constants. tokens.json carries no motion section, so",
        "//! these are pinned from the design system README (Animation):",
        "//! the duration scale, the default UI duration and the preferred",
        "//! curve. The six named easing curves are listed there without",
        "//! published control points; they land here when a component",
        "//! needs them.",
        "",
        "/// The approved duration scale, ms.",
        "pub const DURATION_SCALE: &[f32] = &[50.0, 100.0, 200.0, 300.0, 500.0, 700.0, 1000.0];",
        "",
        "/// The default UI duration, ms.",
        "pub const DURATION_DEFAULT: f32 = 240.0;",
        "",
        "/// The preferred curve, cubic-bezier(0.2, 0.8, 0.2, 1),",
        "/// near-equivalent to Material 3 emphasized-decelerate.",
        "pub const EASING_STANDARD: [f32; 4] = [0.2, 0.8, 0.2, 1.0];",
        "",
    ]
    return "\n".join(lines)


# ---- snapshot fixture (real values even under --stub) -------------------


def snapshot_value(rgba: tuple[int, int, int, int]) -> str:
    r, g, b, a = rgba
    if a == 255:
        return f"#{r:02x}{g:02x}{b:02x}"
    return f"rgba({r},{g},{b},{a})"


def gen_snapshot(data: dict) -> str:
    themes = [t["id"] for t in data["color"]["themes"]]
    constants, roles, aliases = split_token_maps(data)
    lines = [
        f"# {HEADER}",
        "# One line per role and theme: <role> <theme> <value>.",
        "# The fixture the crate tests validate the generated code against.",
    ]
    for role in roles:
        for theme in themes:
            rgba = resolve(role, theme, constants, roles, aliases)
            lines.append(f"{role} {theme} {snapshot_value(rgba)}")
    lines.append("")
    return "\n".join(lines)


# ---- main ---------------------------------------------------------------


def main() -> None:
    stub = "--stub" in sys.argv[1:]
    if not TOKENS_JSON.is_file():
        die(f"tokens.json not found at {TOKENS_JSON}")
    data = json.loads(TOKENS_JSON.read_text())

    outputs = {
        "colors.rs": gen_colors(data, stub),
        "shadows.rs": gen_shadows(data, stub),
        "spacing.rs": scalar_module(data, "spacing", "spacing", "The spacing scale: 4px base, approved steps only.", stub),
        "radii.rs": scalar_module(data, "radius", "radii", "The corner-radius scale: moderate, never sharp, never overly rounded.", stub),
        "type_scale.rs": scalar_module(data, "typeScale", "type_scale", "The type scale: modular, 1.250 ratio, anchored at 16px body.", stub),
        "leading.rs": scalar_module(data, "leading", "leading", "Line heights, unitless.", stub),
        "tracking.rs": scalar_module(data, "tracking", "tracking", "Letter spacing, in em.", stub),
        "breakpoints.rs": scalar_module(data, "breakpoint", "breakpoints", "The six layout breakpoints, in px.", stub),
        "containers.rs": scalar_module(data, "container", "containers", "Container max widths, in px (the two 100% mobile/tablet steps are viewport-relative).", stub),
        "icons.rs": scalar_module(data, "icon", "icons", "Material Symbols Outlined settings: sizes in px, axis values unitless.", stub),
        "motion.rs": gen_motion(),
        "snapshot.txt": gen_snapshot(data),
    }
    for name, content in outputs.items():
        (OUT_DIR / name).write_text(content)
        print(f"wrote src/tokens/{name}{' (stub values)' if stub and name != 'snapshot.txt' else ''}")


if __name__ == "__main__":
    main()
